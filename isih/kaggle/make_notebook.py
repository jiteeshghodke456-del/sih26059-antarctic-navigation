            "    im = ax.imshow(img, cmap=cmap, **kw)\n"
            "    ax.set_title(title, fontsize=12); ax.axis('off')\n"
            "    plt.colorbar(im, ax=ax, fraction=0.046)\n"
            "plt.suptitle('Antarctic sea-ice concentration — red means our model beat the raw forecast',\n"
            "             fontsize=13)\n"
            "plt.tight_layout(); plt.savefig('demo_comparison.png', dpi=140, bbox_inches='tight')\n"
