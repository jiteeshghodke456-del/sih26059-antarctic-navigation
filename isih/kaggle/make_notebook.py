"""Generate the self-contained Kaggle notebook from the real source files.

The notebook must run on Kaggle without access to this private repo, so the
project's own modules are embedded into it. Embedding by hand would drift out
of sync with the sources the moment either changes, so it is generated instead:
re-run this script after touching unet.py / grid.py and the notebook is current
again.

    python isih/kaggle/make_notebook.py
"""

