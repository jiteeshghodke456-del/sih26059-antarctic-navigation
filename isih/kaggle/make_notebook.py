def md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": text.splitlines(keepends=True)}


def code(text: str) -> dict:
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": text.splitlines(keepends=True),
    }


def build_embed_cell() -> str:
    parts = [
        "# Project modules, embedded from the repo so this notebook runs standalone.",
        "# Generated by isih/kaggle/make_notebook.py -- do not edit here, edit the",
        "# source files and regenerate, otherwise the two silently diverge.",
        "from pathlib import Path",
        "Path('isih_src').mkdir(exist_ok=True)",
        "",
    ]
    for name, path in EMBED.items():
        source = path.read_text()
        parts.append(f"# ---- {name} " + "-" * (60 - len(name)))
        parts.append(f"Path('isih_src/{name}').write_text('''{source.replace(chr(92), chr(92) * 2).replace(chr(39) * 3, chr(92) + chr(39) * 3)}''')")
        parts.append("")
    parts.append("import sys; sys.path.insert(0, 'isih_src')")
    parts.append("print('modules written:', sorted(p.name for p in Path('isih_src').glob('*.py')))")
    return "\n".join(parts)


