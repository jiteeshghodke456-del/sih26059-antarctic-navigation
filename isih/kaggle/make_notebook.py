            "import matplotlib.pyplot as plt\n"
            "\n"
            "xb, yb, mb = next(iter(test_loader))\n"
            "with torch.no_grad():\n"
            "    pred = apply_correction(xb[:, :1].to(device), model(xb.to(device))).cpu()\n"
